def _column_names(connection: sqlite3.Connection | PostgresConnection, table_name: str) -> set[str]:
    if _is_postgres_connection(connection):
        rows = connection.execute(
            """
            SELECT column_name AS name
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = ?
            """,
            (table_name,),
        ).fetchall()
        return {row["name"] for row in rows}
    return {
        row["name"] for row in connection.execute(f"PRAGMA table_info({table_name})").fetchall()
    }


def _normalize_column_definition(connection: sqlite3.Connection | PostgresConnection, definition: str) -> str:
    if not _is_postgres_connection(connection):
        return definition
    return definition.replace("REAL", "DOUBLE PRECISION")


def _ensure_column(connection: sqlite3.Connection | PostgresConnection, table_name: str, column_name: str, definition: str) -> None:
    existing_columns = _column_names(connection, table_name)
    if column_name not in existing_columns:
        connection.execute(f"ALTER TABLE {table_name} ADD COLUMN {column_name} {_normalize_column_definition(connection, definition)}")


