class PostgresCursor:
    def __init__(self, cursor: Any, *, lastrowid: int | None = None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    @property
    def rowcount(self) -> int:
        return int(getattr(self._cursor, "rowcount", 0) or 0)

    def fetchone(self) -> Any:
        return self._cursor.fetchone()

    def fetchall(self) -> list[Any]:
        return self._cursor.fetchall()


class PostgresConnection:
    dialect = "postgres"

    def __init__(self, dsn: str):
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:  # pragma: no cover - dependency error is explicit at runtime
            raise RuntimeError("PostgreSQL support requires psycopg; run `pip install -r requirements.txt`.") from exc

        self._connection = psycopg.connect(dsn, row_factory=dict_row)

    def execute(self, sql: str, parameters: tuple[Any, ...] | list[Any] = ()) -> PostgresCursor:
        translated_sql, returning_id = _translate_postgres_sql(sql)
        cursor = self._connection.execute(translated_sql, parameters)
        lastrowid = None
        if returning_id:
            row = cursor.fetchone()
            if row is not None:
                lastrowid = int(row["id"])
        return PostgresCursor(cursor, lastrowid=lastrowid)

    def executemany(self, sql: str, parameters_seq: list[tuple[Any, ...]] | tuple[tuple[Any, ...], ...]) -> PostgresCursor:
        translated_sql, returning_id = _translate_postgres_sql(sql)
        if returning_id:
            translated_sql = re.sub(r"\s+RETURNING\s+id\s*$", "", translated_sql, flags=re.IGNORECASE)
        cursor = self._connection.cursor()
        cursor.executemany(translated_sql, parameters_seq)
        return PostgresCursor(cursor)

    def executescript(self, sql_script: str) -> None:
        for statement in _split_sql_script(_translate_postgres_schema(sql_script)):
            self.execute(statement)

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()

    def __enter__(self) -> "PostgresConnection":
        return self

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> None:
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        self.close()


def _is_postgres_dsn(value: str) -> bool:
    return value.startswith(("postgresql://", "postgres://"))


def _is_postgres_connection(connection: Any) -> bool:
    return getattr(connection, "dialect", "sqlite") == "postgres"


def try_postgres_advisory_lock(connection: Any, key: str) -> bool:
    if not _is_postgres_connection(connection):
        return True
    row = connection.execute("SELECT pg_try_advisory_lock(hashtext(?)) AS locked", (key,)).fetchone()
    return bool(row and row["locked"])


def release_postgres_advisory_lock(connection: Any, key: str) -> None:
    if not _is_postgres_connection(connection):
        return
    connection.execute("SELECT pg_advisory_unlock(hashtext(?)) AS unlocked", (key,))


def _split_sql_script(sql_script: str) -> list[str]:
    return [statement.strip() for statement in sql_script.split(";") if statement.strip()]


def _translate_placeholders(sql: str) -> str:
    return sql.replace("?", "%s")


def _insert_table_name(sql: str) -> str | None:
    match = re.match(r"\s*INSERT\s+INTO\s+([a-zA-Z_][a-zA-Z0-9_]*)", sql, flags=re.IGNORECASE)
    return match.group(1) if match else None


def _translate_postgres_sql(sql: str) -> tuple[str, bool]:
    stripped = sql.strip()
    table_name = _insert_table_name(stripped)
    returning_id = (
        table_name in AUTOINCREMENT_TABLES
        and " RETURNING " not in stripped.upper()
        and " ON CONFLICT " not in stripped.upper()
    )
    translated = _translate_placeholders(stripped)
    if returning_id:
        translated = f"{translated} RETURNING id"
    return translated, returning_id


def _translate_postgres_schema(schema_sql: str) -> str:
    translated = schema_sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    translated = translated.replace("REAL", "DOUBLE PRECISION")
    return translated


def connect(database_path: str | Path) -> sqlite3.Connection | PostgresConnection:
    database_value = str(database_path)
    if _is_postgres_dsn(database_value):
        return PostgresConnection(database_value)
    connection = sqlite3.connect(database_value)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


